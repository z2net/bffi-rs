    #[test]
    fn push_backpressures_until_drained() {
        use super::{PUSH_CAPACITY, spawn_push};
        let (handle, ctx) = spawn_push::<i32>().expect("spawned");
        // Fill the buffer exactly.
        for i in 0..PUSH_CAPACITY as i32 {
            push_now(&ctx, i);
        }
        // The next push parks: the buffer is full and nothing drains.
        let mut fut = ctx.push(999);
        assert!(
            futures_poll(&mut fut).is_none(),
            "a parked push must stay pending while the buffer is full"
        );
        // Draining frees room and wakes the producer.
        match next_chunk(handle, PUSH_CAPACITY).expect("chunk") {
            Chunk::Items(items) => assert_eq!(items.len(), PUSH_CAPACITY),
            Chunk::Done => panic!("items were pushed"),
        }
        assert!(
            futures_poll(&mut fut).is_some(),
            "the waker fired: the push resolved"
        );
        let mut seen = Vec::new();
        while let Chunk::Items(items) = next_chunk(handle, PUSH_CAPACITY).expect("chunk") {
            seen.extend(items);
            if seen.len() == 1 {
                break;
            }
        }
        assert_eq!(seen.len(), 1, "exactly the parked item remains");
        // The producer never completed: the empty live buffer stays
        // Pending (the poll contract, not an error).
        assert!(matches!(
            next_chunk(handle, PUSH_CAPACITY),
            Err(StreamError::Pending)
        ));
    }

