//! # bffi-stream
//!
//! Streams over user iterators and producers (B2): a
//! `#[bffi_stream]` export hands JavaScript a stream handle; the
//! generic `bffi_stream_next` export pulls chunks. The items are
//! pre-encoded wire records (`Vec<u8>` of one complete
//! `[tag][payload]` each), so the chunk crosses as one `TAG_SEQ`
//! payload through the ordinary transient-buffer channel - no new
//! ABI shapes.
//!
//! Two models share one table and one pull ABI:
//!
//! - **pull** (B2.1): the entry holds a user iterator; `next` runs
//!   it on the JS thread under the entry mutex (the iterator must
//!   not block indefinitely);
//! - **push** (B2.2): the entry holds a bounded buffer fed by a
//!   producer future running on the async executor
//!   ([`Ctx::push`](Ctx::push) parks with backpressure when the
//!   buffer is full). An empty live buffer reports
//!   [`StreamError::Pending`] - not an error, a retry hint: the JS
//!   wrapper waits a tick and pulls again (the same explicit-drain
//!   philosophy as `pumpUntil`; the buffer is shared memory, so the
//!   pull IS the delivery).
//!
//! A panic inside a pull iterator poisons that stream only
//! (`catch_unwind` marks the entry errored; the table survives).
//! Dropping a stream marks it done; a producer pushing afterwards
//! sees [`StreamError::Closed`] and its future ends.
//!
//! The stream table reuses the global [`Registry`] under tag
//! `0x0600` (claimed in [`bffi::core::handle`]), mirroring the task
//! table of `bffi-async`.

// Internal module aliases (the pre-merge crate names).
use crate::bffi_core;
use std::collections::VecDeque;
use std::sync::{Arc, Mutex, OnceLock};
use std::task::Waker;

use bffi_core::{Handle, Registry, TypeTag};

pub mod abi;

/// The type tag of the stream table.
const STREAM_TAG: TypeTag = TypeTag(0x0600);

/// The bounded buffer capacity of a push stream: a producer pushing
/// into a full buffer parks (its `push` future stays pending) until
/// the JS side drains room.
pub(crate) const PUSH_CAPACITY: usize = 256;

/// The wire form of one stream item: a complete `[tag][payload]`
/// record.
pub type EncodedItem = Vec<u8>;

/// A type that can cross a stream as one item record. Implemented
/// for the scalar matrix (numbers, `i64`, `u64`, `bool`, `String`,
/// `Vec<u8>`) and generated by `#[derive(BffiRecord)]` /
/// `#[derive(BffiEnum)]` for composites; `Result<T, E>` items encode
/// their `Err` as an error record (TAG 11).
pub trait BffiStreamItem {
    /// Appends the item as one complete wire record.
    fn encode_into(&self, out: &mut Vec<u8>);
}

macro_rules! stream_item_int {
    ($($ty:ty),* => $encoder:ident) => {
        $(
            impl BffiStreamItem for $ty {
                fn encode_into(&self, out: &mut Vec<u8>) {
                    crate::bffi_types::wire::$encoder(out, (*self).into());
                }
            }
        )*
    };
}

stream_item_int!(i8, i16, i32, u8, u16 => encode_i32);

impl BffiStreamItem for u32 {
    fn encode_into(&self, out: &mut Vec<u8>) {
        // The f64 record is exact over the whole u32 range.
        crate::bffi_types::wire::encode_f64(out, f64::from(*self));
    }
}

