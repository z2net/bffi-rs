    /// Pushes and asserts the item landed immediately (room was
    /// available).
    fn push_now<T: super::BffiStreamItem>(ctx: &super::Ctx<T>, item: T) {
        assert!(
            futures_poll(&mut ctx.push(item)).is_some(),
            "a push below capacity must resolve immediately"
        );
    }

    /// Polls a future once (no executor): `Some(output)` when ready.
    fn futures_poll<F>(fut: &mut F) -> Option<F::Output>
    where
        F: std::future::Future + Unpin,
    {
        use std::task::Poll;
        let waker = std::task::Waker::noop();
        let mut cx = std::task::Context::from_waker(waker);
        match std::pin::Pin::new(fut).poll(&mut cx) {
            Poll::Ready(output) => Some(output),
            Poll::Pending => None,
        }
    }
